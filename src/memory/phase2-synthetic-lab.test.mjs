import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {createHash} from "node:crypto";
import {SyntheticMemoryLab} from "./phase2-synthetic-lab.mjs";

const frozen=JSON.parse(readFileSync(new URL("../../docs/a0/roster-frozen-2026-11-07.json",import.meta.url),"utf8"));
const chiefs=frozen.records.filter(x=>x.Role==="Chief");
const specialists=frozen.records.filter(x=>x.Role==="Specialist");
const first=specialists[0];
const peer=specialists.find(x=>x["Agent ID"]!==first["Agent ID"]&&x.Department===first.Department);
const other=specialists.find(x=>x.Department!==first.Department);
const record=(lab,actor,content="SYNTHETIC: example class notes",options={})=>
 lab.addCandidate(actor,{content,...options});
const create=()=>new SyntheticMemoryLab(frozen);
test("185 approved IDs can receive distinct unforgeable-in-this-lab test contexts",()=>{
 const lab=create(),owner=lab.testOwner();
 assert.equal(chiefs.length,25);
 assert.equal(specialists.length,160);
 assert.equal(new Set(frozen.records.map(x=>x["Agent ID"])).size,185);
 for(const row of frozen.records){
  const actor=lab.testActor(row["Agent ID"]);
  const created=record(lab,actor,"SYNTHETIC: "+row["Agent ID"]);
  assert.equal(created.status,"candidate");
  assert.equal(lab.find(actor,{query:row["Agent ID"]}).length,0);
  lab.acceptForTest(owner,created.memoryId);
  assert.equal(lab.find(actor,{query:row["Agent ID"]}).length,1);
 }
 assert.equal(lab.getStatus().records,185);
 assert.equal(lab.getStatus().persistentDatabase,false);
 assert.equal(lab.getStatus().realOwnerAuthentication,false);
 assert.equal(lab.getStatus().realMemoryAccess,false);
});
test("candidate, agent isolation, fabricated identity and unexpected data are denied",()=>{
 const lab=create(),owner=lab.testOwner();
 const agent=lab.testActor(first["Agent ID"]);
 const same=lab.testActor(peer["Agent ID"]);
 const outsider=lab.testActor(other["Agent ID"]);
 const created=record(lab,agent);
 assert.deepEqual(lab.find(agent,{query:"example"}),[]);
 assert.throws(()=>lab.find(Object.freeze({}),{query:"example"}),/FORGED_OR_FOREIGN_TEST_CONTEXT/);
 assert.throws(()=>lab.find({agentId:first["Agent ID"]},{query:"example"}),/FORGED_OR_FOREIGN_TEST_CONTEXT/);
 assert.throws(()=>lab.testActor("fake-agent"),/UNKNOWN_TEST_AGENT_OR_PROJECT/);
 assert.throws(()=>record(lab,agent,"private non-synthetic text"),/INVALID_SYNTHETIC_CANDIDATE/);
 assert.throws(()=>lab.addCandidate(agent,{content:"SYNTHETIC: sample",dataClass:"OWNER_PRIVATE"}),/UNSUPPORTED_SYNTHETIC_INPUT/);
 assert.throws(()=>lab.find(agent,{query:"example",ownerApproved:true}),/UNSUPPORTED_SYNTHETIC_QUERY/);
 assert.throws(()=>lab.acceptForTest(agent,created.memoryId),/SYNTHETIC_OWNER_CONTEXT_REQUIRED/);
 lab.acceptForTest(owner,created.memoryId);
 assert.equal(lab.find(agent,{query:"example"}).length,1);
 assert.equal(lab.find(same,{query:"example"}).length,0);
 assert.equal(lab.find(outsider,{query:"example"}).length,0);
});
