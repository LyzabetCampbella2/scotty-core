test("correction creates a new unapproved version; archival and deletion remove visibility",()=>{
 const lab=create(),owner=lab.testOwner(),actor=lab.testActor(first["Agent ID"]);
 const original=record(lab,actor,"SYNTHETIC: old fact");
 lab.acceptForTest(owner,original.memoryId);
 const next=lab.correctForTest(owner,original.memoryId,"SYNTHETIC: corrected fact","test-only correction");
 assert.equal(next.needsSeparateSyntheticAcceptance,true);
 assert.equal(next.realCorrectionPerformed,false);
 assert.equal(lab.find(actor,{query:"old fact"}).length,0);
 assert.equal(lab.find(actor,{query:"corrected fact"}).length,0);
 lab.acceptForTest(owner,next.memoryId);
 const revised=lab.find(actor,{query:"corrected fact"});
 assert.equal(revised.length,1);
 assert.equal(revised[0].version,2);
 assert.equal(revised[0].supersedesId,original.memoryId);
 lab.archiveForTest(owner,next.memoryId);
 assert.equal(lab.find(actor,{query:"corrected"}).length,0);
 const deletion=lab.deleteForTest(owner,next.memoryId);
 assert.equal(deletion.deletedFromSimulation,true);
 assert.equal(deletion.realDataDeletion,false);
 assert.equal(deletion.backupsReconciled,false);
 const exported=lab.exportForRestartTest(owner);
 assert.equal(exported.payload.includes("SYNTHETIC: corrected fact"),false);
 assert.throws(()=>lab.deleteForTest(owner,next.memoryId),/ALREADY_DELETED/);
});
test("TTL expiry and simulated restart preserve synthetic access rules, not session authority",()=>{
 const lab=create(),owner=lab.testOwner(),actor=lab.testActor(first["Agent ID"]);
 const expire="2026-11-08T12:00:00Z";
 const item=record(lab,actor,"SYNTHETIC: one day event",{expiresAt:expire});
 lab.acceptForTest(owner,item.memoryId);
 assert.equal(lab.find(actor,{query:"one day"}).length,1);
 const snapshot=lab.exportForRestartTest(owner);
 assert.equal(snapshot.isActualBackup,false);
 assert.equal(snapshot.containsRealData,false);
 const restored=SyntheticMemoryLab.restoreForTest(frozen,snapshot);
 assert.equal(restored.getStatus().persistentDatabase,false);
 assert.throws(()=>restored.find(actor,{query:"one day"}),/FORGED_OR_FOREIGN_TEST_CONTEXT/);
 const newActor=restored.testActor(first["Agent ID"]),newOwner=restored.testOwner();
 assert.equal(restored.find(newActor,{query:"one day"}).length,1);
 restored.advanceClockForTest(newOwner,expire);
 assert.equal(restored.find(newActor,{query:"one day"}).length,0);
 assert.equal(lab.find(actor,{query:"one day"}).length,1);
 assert.ok(restored.auditForTest(newOwner).some(e=>e.type==="clock-advanced"));
});
test("snapshot tampering or real-data injection is rejected; no actual backup claimed",()=>{
 const lab=create(),owner=lab.testOwner(),actor=lab.testActor(first["Agent ID"]);
 const item=record(lab,actor,"SYNTHETIC: safe only");
 lab.acceptForTest(owner,item.memoryId);
 const backup=lab.exportForRestartTest(owner);
 assert.throws(()=>SyntheticMemoryLab.restoreForTest(frozen,{...backup,payload:backup.payload+" "}),/INVALID_SYNTHETIC_RESTART_FIXTURE/);
 const mutated=JSON.parse(backup.payload);
 mutated.records[0].dataClass="OWNER_PRIVATE";
 const payload=JSON.stringify(mutated);
 assert.throws(()=>SyntheticMemoryLab.restoreForTest(frozen,{...backup,payload,digest:createHash("sha256").update(payload).digest("hex")}),/INVALID_SYNTHETIC_RECORD/);
 assert.throws(()=>SyntheticMemoryLab.restoreForTest(frozen,{...backup,isActualBackup:true}),/INVALID_SYNTHETIC_RESTART_FIXTURE/);
 assert.equal(lab.getStatus().realMemoryAccess,false);
});
