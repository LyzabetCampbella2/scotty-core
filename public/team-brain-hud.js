/* Owner-approved Team Brain routing for both typed HUD commands and recognized speech.
 * Never sends private text to Cloudflare without per-request owner consent.
 * Mission checkpoints and reviewed knowledge are separate stores.
 */
(function(root){
 'use strict';
 let pending=null,last=null;
 const approvalPhrase=/^(?:(?:hey\\s+)?scotty[,\\s-]+)?approve (?:this )?team brain request (?:and )?(?:confirm(?:ing)? )?no private data[.!?]*$/i;
 const cancelPhrase=/^(?:(?:hey\\s+)?scotty[,\\s-]+)?cancel (?:this )?team brain request[.!?]*$/i;
 const safeText=value=>String(value||'').trim();
 const short=value=>safeText(value).slice(0,1800);
 function shouldRoute(text){
  const s=safeText(text);
  if(!s||s.length>500||/^(?:remember|save to memory|delete|send|publish|approve|restore|create (?:a )?(?:project|task|folder))\\b/i.test(s))return false;
  return /\\bteam brain\\b|\\b(?:agents|specialists|chiefs)\\s+(?:to|for|review|analy[sz]e|help)\\b|\\b(?:ask|use|bring in|coordinate|assemble|assign|recommend|consult|have)\\s+(?:(?:my|the|your|scotty'?s)\\s+)?(?:agents|chiefs|specialists|team)\\b|\\b(?:review|analy[sz]e|draft|plan|outline)\\b.{0,120}\\b(?:with|using|through)\\s+(?:(?:my|the|your)\\s+)?(?:agents|chiefs|specialists|team)\\b/i.test(s);
 }
 function node(tag,text){
  const el=document.createElement(tag);if(text!==undefined)el.textContent=text;return el;
 }
 function card(title){
  const el=node('section');el.setAttribute('role','region');
  el.style.cssText='position:fixed;z-index:999999;left:12px;right:12px;bottom:18px;max-width:600px;margin:auto;padding:16px;border:1px solid #68e6f0;border-radius:12px;color:#e9fdff;background:#071524;box-shadow:0 12px 42px #000c;font:14px/1.5 system-ui,sans-serif;max-height:78vh;overflow:auto';
  const heading=node('h3',title);heading.style.cssText='font-size:16px;margin:0 0 8px';el.appendChild(heading);
  document.body.appendChild(el);return el;
 }
 function check(panel,label){
  const wrap=node('label');wrap.style.cssText='display:block;margin:8px 0';
  const input=node('input');input.type='checkbox';input.style.marginRight='8px';
  wrap.appendChild(input);wrap.appendChild(node('span',label));panel.appendChild(wrap);return input;
 }
 function button(panel,label,action){
  const b=node('button',label);b.type='button';b.style.cssText='margin:8px 8px 0 0;padding:9px;border-radius:7px;background:#10384b;color:#efffff;border:1px solid #6ee7ef';
  b.onclick=action;panel.appendChild(b);return b;
 }
 function approve(question,signal,speak){
  return new Promise(resolve=>{
   if(pending)pending.finish(false);
   const panel=card('SCOTTY Team Brain · owner approval');
   panel.appendChild(node('p','SCOTTY proposes sending this request to the isolated Cloudflare Team Brain. No data has been sent yet.'));
   const excerpt=node('p',short(question));excerpt.style.overflowWrap='anywhere';panel.appendChild(excerpt);
   const a=check(panel,'I approve this one Team Brain request.');
   const b=check(panel,'I agree the request will be sent to Cloudflare Workers AI.');
   const c=check(panel,'I verified it contains no private, client, account or production information.');
   let timer;
   function finish(granted){
    if(pending!==entry)return;
    pending=null;clearTimeout(timer);signal?.removeEventListener('abort',cancel);
    panel.remove();resolve(Boolean(granted));
   }
   const cancel=()=>finish(false);
   const entry={finish,question,createdAt:Date.now()};
   pending=entry;
   button(panel,'Approve and send',()=>finish(a.checked&&b.checked&&c.checked));
   button(panel,'Cancel / do not send',cancel);
   panel.appendChild(node('p','Voice: say “Scotty, approve this Team Brain request no private data” or “Scotty, cancel this Team Brain request.” Approvals during playback are ignored.'));
   signal?.addEventListener('abort',cancel,{once:true});
   timer=setTimeout(cancel,180000);
   if(signal?.aborted)cancel();
   else if(typeof speak==='function')Promise.resolve().then(()=>speak('Team Brain approval required. Confirm the question contains no private data. You can approve this Team Brain request or cancel it.')).catch(()=>{});
  });
 }
 function handleSpokenConsent(raw,meta={}){
  const s=safeText(raw);if(!pending)return false;
  if(!approvalPhrase.test(s)&&!cancelPhrase.test(s))return false;
  // Echoes, speech generated by SCOTTY and transcripts captured during playback cannot approve.
  if(meta.capturedDuringSpeech===true||root.speaking===true)return true;
  if(Date.now()-pending.createdAt>180000){pending.finish(false);return true;}
  pending.finish(approvalPhrase.test(s));return true;
 }
 async function call(path,options={}){
  const response=await fetch('/api/independent-brain/'+path,{
   method:options.data?'POST':'GET',credentials:'same-origin',cache:'no-store',
   headers:options.data?{'content-type':'application/json'}:{},
   ...(options.data?{body:JSON.stringify(options.data)}:{}),
   ...(options.signal?{signal:options.signal}:{})
  });
  let json;
  try{json=await response.json()}catch{throw Error('Team Brain returned invalid JSON.');}
  if(!response.ok||json.ok===false)throw Error(safeText(json.message||json.error||'Team Brain request failed').slice(0,240));
  return json;
 }
 function offerReviewedMemory(answer,signal){
  if(!safeText(answer))return;
  const panel=card('Optional · save a reviewed SCOTTY memory');
  panel.appendChild(node('p','The mission is saved separately in the Cloudflare mission log. Generated answers are NOT automatically treated as facts. Review and edit this note before saving.'));
  const title=node('input');title.value='Owner-reviewed Team Brain answer';title.maxLength=160;title.style.cssText='box-sizing:border-box;width:100%;padding:8px';panel.appendChild(title);
  const body=node('textarea');body.value=short(answer);body.maxLength=1800;body.rows=5;body.style.cssText='box-sizing:border-box;width:100%;padding:8px;margin-top:8px';panel.appendChild(body);
  const reviewed=check(panel,'I reviewed and approve the wording and SCOTTY-only scope.');
  const privacy=check(panel,'This note contains no private, client or production data.');
  const status=node('p','Not saved as knowledge.');panel.appendChild(status);
  button(panel,'Save reviewed memory',async()=>{
   if(!reviewed.checked||!privacy.checked||!safeText(title.value)||!safeText(body.value)){status.textContent='Complete both approvals and review the note text first.';return;}
   status.textContent='Saving and verifying…';
   try{
    const result=await call('memory',{data:{agentId:'scotty',scope:'agent',title:safeText(title.value),content:safeText(body.value),approved:true,noPrivateDataConfirmed:true},signal});
    const read=await call('memory?agentId=scotty',{signal});
    const verified=Boolean(result.note?.id&&(read.notes||[]).some(n=>n.id===result.note.id));
    status.textContent=verified?'Saved and independently verified in SCOTTY-only reviewed memory.':'Write returned, but the memory read-back was not verified.';
    last={...last,reviewedMemoryVerified:verified,memoryNoteId:result.note?.id||null};
   }catch(e){status.textContent='Memory not verified: '+e.message;}
  });
  button(panel,'Close without saving',()=>panel.remove());
 }
 async function run(question,{signal,speak}={}){
  if(!shouldRoute(question))throw Error('Team routing requested for an unsupported command.');
  if(!(await approve(question,signal,speak)))return {cancelled:true};
  if(signal?.aborted)return {cancelled:true};
  const missionId=crypto.randomUUID();
  const data=await call('team',{data:{question,teamSize:1,missionId,ownerApproved:true,shareWithCloudflare:true,noPrivateDataConfirmed:true},signal});
  let missionVerified=false;
  try{
   const history=await call('missions',{signal});
   missionVerified=Boolean(data.missionPersisted&&(history.missions||[]).some(m=>m.id===missionId&&m.status===data.status&&m.result?.answer===data.answer));
  }catch{}
  const answer=safeText(data.answer);
  const reply=answer||(data.status==='needs-clarification'?'The team needs a more specific question.': 'Team Brain did not produce a complete answer. Check the Brain Lab mission history.');
  last={missionId,missionVerified,reviewedMemoryVerified:false,status:data.status,answer};
  if(answer&&data.status==='completed')offerReviewedMemory(answer,signal);
  return {ok:true,reply,provider:'cloudflare-team',missionId,missionVerified,teamStatus:data.status,reviewedMemoryVerified:false};
 }
 root.SCOTTYTeamBrain={shouldRoute,run,handleSpokenConsent,get last(){return last},get awaitingApproval(){return Boolean(pending)}};
})(window);
